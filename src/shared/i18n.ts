export type MessageKey = keyof typeof en;

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "es";
}

export function intlTag(locale: Locale): string {
  return locale === "es" ? "es-AR" : "en-US";
}

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let text: string = locale === "es" ? es[key] : en[key];
  if (!vars) return text;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function trafficLabel(locale: Locale, source: string): string {
  const key = `traffic.${source}` as MessageKey;
  if (key in en) return translate(locale, key);
  return source
    .replaceAll("_", " ")
    .toLowerCase()
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

export function formatCount(locale: Locale, n: number, digits = 0): string {
  return n.toLocaleString(intlTag(locale), {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  });
}
